KEYBOARD    = $0200
DISPLAY     = $0400
DISK_CMD    = $0320
DISK_SEC    = $0321
DISK_BUFL   = $0322
DISK_BUFH   = $0323
PROG_ADDR   = $2000
GAME_ADDR   = $2100

CUR_L       = $10
CUR_H       = $11
COL         = $12
TMP         = $13
LEN         = $14
CMDCH       = $15
SRC_L       = $16
SRC_H       = $17
DST_L       = $18
DST_H       = $19
SECN        = $1A
PAGEH       = $1B
END_SEC     = $1C

    .ORG $8000

RESET:
    SEI
    CLD
    LDX #$FF
    TXS
    JSR SYS_CLEAR
    LDA #$00
    STA CUR_L
    STA COL
    LDA #$04
    STA CUR_H
    JMP SHELL_PROMPT

BRK_HANDLER:
    LDX #$FF
    TXS
    JMP SHELL_PROMPT

SYS_CLEAR:
    LDX #$00
    LDA #$20
CLEAR_LOOP:
    STA $0400,X
    STA $0500,X
    STA $0600,X
    STA $0700,X
    INX
    BNE CLEAR_LOOP
    RTS

SYS_GETCHAR:
    LDA KEYBOARD
    BEQ SYS_GETCHAR
    RTS

SYS_PUTCHAR:
    STY TMP
    CMP #$0D
    BEQ PC_ENTER
    CMP #$08
    BEQ PC_BKSP
    LDY #$00
    STA (CUR_L),Y
    JSR CUR_INC
    JMP PC_DONE

PC_ENTER:
    JSR NEWLINE
    JMP PC_DONE

PC_BKSP:
    LDA CUR_L
    BNE PB_1
    DEC CUR_H
PB_1:
    DEC CUR_L
    LDA COL
    BNE PB_2
    LDA #$28
    STA COL
PB_2:
    DEC COL
    LDA #$20
    LDY #$00
    STA (CUR_L),Y

PC_DONE:
    LDY TMP
    RTS

CUR_INC:
    INC CUR_L
    BNE CI_1
    INC CUR_H
CI_1:
    INC COL
    LDA COL
    CMP #$28
    BNE CI_2
    LDA #$00
    STA COL
CI_2:
    LDA CUR_H
    CMP #$07
    BNE CI_DONE
    LDA CUR_L
    CMP #$E8
    BCC CI_DONE
    JSR SCROLL
    LDA #$C0
    STA CUR_L
    LDA #$07
    STA CUR_H
    LDA #$00
    STA COL
CI_DONE:
    RTS

NEWLINE:
    JSR CUR_INC
    LDA COL
    BNE NEWLINE
    RTS

SCROLL:
    LDA #$00
    STA DST_L
    LDA #$04
    STA DST_H
    LDA #$28
    STA SRC_L
    LDA #$04
    STA SRC_H
    LDX #$03
SC_PAGE:
    LDY #$00
SC_BYTE:
    LDA (SRC_L),Y
    STA (DST_L),Y
    INY
    BNE SC_BYTE
    INC SRC_H
    INC DST_H
    DEX
    BNE SC_PAGE
    LDY #$00
SC_REST:
    LDA (SRC_L),Y
    STA (DST_L),Y
    INY
    CPY #$C0
    BNE SC_REST
    LDA #$20
    LDY #$00
SC_CLR:
    STA $07C0,Y
    INY
    CPY #$28
    BNE SC_CLR
    RTS

PRINT_OK:
    LDA #$4F
    JSR SYS_PUTCHAR
    LDA #$4B
    JSR SYS_PUTCHAR
    LDA #$0D
    JSR SYS_PUTCHAR
    RTS

SHELL_PROMPT:
    LDA COL
    BEQ SP_GO
    LDA #$0D
    JSR SYS_PUTCHAR
SP_GO:
    LDA #$00
    STA LEN
    LDA #$3E
    JSR SYS_PUTCHAR

SHELL_LOOP:
    JSR SYS_GETCHAR
    CMP #$0D
    BEQ SH_ENTER
    CMP #$08
    BEQ SH_BKSP
    CMP #$20
    BCC SHELL_LOOP
    LDX LEN
    CPX #$F0
    BCS SHELL_LOOP
    CPX #$00
    BNE SH_KEEP
    STA CMDCH
SH_KEEP:
    INC LEN
    JSR SYS_PUTCHAR
    JMP SHELL_LOOP

SH_BKSP:
    LDA LEN
    BEQ SHELL_LOOP
    DEC LEN
    LDA #$08
    JSR SYS_PUTCHAR
    JMP SHELL_LOOP

SH_ENTER:
    LDA #$0D
    JSR SYS_PUTCHAR
    LDA LEN
    CMP #$01
    BNE SH_NONE
    LDA CMDCH
    CMP #$45
    BEQ CMD_EDIT
    CMP #$52
    BEQ CMD_RUN
    CMP #$53
    BEQ CMD_SAVE
    CMP #$4C
    BEQ CMD_LOAD
    CMP #$47
    BEQ CMD_GAME
SH_NONE:
    JMP SHELL_PROMPT

CMD_RUN:
    JSR PROG_ADDR
    JMP SHELL_PROMPT

CMD_EDIT:
    LDY #$00
EDIT_LOOP:
    JSR SYS_GETCHAR
    CMP #$1B
    BEQ EDIT_EXIT
    CMP #$08
    BEQ ED_BKSP
    CMP #$0D
    BEQ ED_STORE
    CMP #$20
    BCC EDIT_LOOP
ED_STORE:
    STA PROG_ADDR,Y
    JSR SYS_PUTCHAR
    INY
    BEQ EDIT_FULL
    JMP EDIT_LOOP

ED_BKSP:
    CPY #$00
    BEQ EDIT_LOOP
    DEY
    LDA PROG_ADDR,Y
    CMP #$0D
    BEQ ED_NOBACK
    LDA #$08
    JSR SYS_PUTCHAR
    JMP EDIT_LOOP
ED_NOBACK:
    INY
    JMP EDIT_LOOP

EDIT_EXIT:
    LDA #$00
    STA PROG_ADDR,Y
EDIT_FULL:
    JMP SHELL_PROMPT

CMD_SAVE:
    LDA #$00
    STA DISK_BUFL
    LDA #$20
    STA DISK_BUFH
    LDA #$01
    STA DISK_SEC
    LDA #$02
    STA DISK_CMD
    JSR PRINT_OK
    JMP SHELL_PROMPT

CMD_LOAD:
    LDA #$00
    STA DISK_BUFL
    LDA #$20
    STA DISK_BUFH
    LDA #$01
    STA DISK_SEC
    LDA #$01
    STA DISK_CMD
    JSR PRINT_OK
    JMP SHELL_PROMPT

CMD_GAME:
    JSR PRINT_MENU
GM_INPUT:
    JSR SYS_GETCHAR
    CMP #$31
    BEQ LOAD_SNAKE
    CMP #$32
    BEQ LOAD_PONG
    CMP #$33
    BEQ LOAD_ROGUE
    JMP GM_INPUT

LOAD_SNAKE:
    LDA #$02
    STA SECN
    LDA #$06
    STA END_SEC
    JMP LOAD_EXEC

LOAD_PONG:
    LDA #$06
    STA SECN
    LDA #$0A
    STA END_SEC
    JMP LOAD_EXEC

LOAD_ROGUE:
    LDA #$0A
    STA SECN
    LDA #$10
    STA END_SEC
    JMP LOAD_EXEC

LOAD_EXEC:
    LDA #$21
    STA PAGEH
    LDA #$00
    STA DISK_BUFL
GM_LOOP:
    LDA PAGEH
    STA DISK_BUFH
    LDA SECN
    STA DISK_SEC
    LDA #$01
    STA DISK_CMD
    INC PAGEH
    INC SECN
    LDA SECN
    CMP END_SEC
    BNE GM_LOOP
    JSR GAME_ADDR
    JSR SYS_CLEAR
    LDA #$00
    STA CUR_L
    STA COL
    LDA #$04
    STA CUR_H
    JMP SHELL_PROMPT

PRINT_MENU:
    LDA #$0D
    JSR SYS_PUTCHAR
    LDA #$53
    JSR SYS_PUTCHAR
    LDA #$45
    JSR SYS_PUTCHAR
    LDA #$4C
    JSR SYS_PUTCHAR
    LDA #$45
    JSR SYS_PUTCHAR
    LDA #$43
    JSR SYS_PUTCHAR
    LDA #$54
